"""MSE 2D analysis — multiscale extension of §4.8 SampEn 2D.

For each conv1 mosaic (3 input channels × 3 seeds × 3 datasets = 27 mosaics),
compute SampEn 2D at scales τ = 1, 2, ..., 10 (Costa et al. 2002/2005, 2D
extension following Silva et al. 2018).

Coarse-graining at scale τ averages non-overlapping τ×τ blocks of the mosaic.
The tolerance r = r_scale × σ is computed ONCE from the τ=1 mosaic and held
fixed across all scales, per Costa's convention.

Outputs (results/mse2d_figs/):
    mse_f1_curves.{pdf,png}     — SampEn₂D × scale τ, 3 datasets, mean ± 1σ
    mse_f2_curves_log.{pdf,png} — same on log-y axis to emphasize crossover
    mse_table.{csv,tex}         — per (dataset, scale) mean ± std
"""
from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.complexity import mse_2d  # noqa: E402

THESIS_ROOT = Path(__file__).resolve().parent.parent
RUNS_DIR    = THESIS_ROOT / "results" / "runs"
OUT         = THESIS_ROOT / "results" / "mse2d_figs"
OUT.mkdir(parents=True, exist_ok=True)

DATASETS = ["PathMNIST", "OrganAMNIST", "BloodMNIST"]
SEEDS    = [42, 123, 2024]
EPOCHS   = 100
MAX_SCALE = 10
R_SCALE  = 0.5     # matches §4.8 calibration

DS_COLOR = {
    "PathMNIST":   "#1f77b4",
    "OrganAMNIST": "#2ca02c",
    "BloodMNIST":  "#d62728",
}

plt.rcParams.update({
    "font.size": 10.5, "axes.titlesize": 11.5, "axes.labelsize": 10.5,
    "legend.fontsize": 9, "figure.dpi": 130,
})


def load_conv1(ds, seed):
    p = RUNS_DIR / f"{ds}_{EPOCHS}ep_seed{seed}" / "checkpoints" / f"resume_epoch_{EPOCHS}.pt"
    if not p.exists():
        return None
    ckpt = torch.load(p, map_location="cpu", weights_only=False)
    return ckpt["model"]["conv1.weight"].numpy()  # [64, 3, 7, 7]


def mosaic_for_channel(conv1_w: np.ndarray, c: int) -> np.ndarray:
    """8×8 grid of 7×7 filters for input channel c → 56×56 image."""
    filters_c = conv1_w[:, c, :, :]
    return filters_c.reshape(8, 8, 7, 7).transpose(0, 2, 1, 3).reshape(56, 56)


def collect():
    rows = []
    for ds in DATASETS:
        for seed in SEEDS:
            conv1 = load_conv1(ds, seed)
            if conv1 is None:
                print(f"missing: {ds} seed={seed}")
                continue
            for c in range(3):
                mosaic = mosaic_for_channel(conv1, c)
                mse = mse_2d(mosaic, max_scale=MAX_SCALE, m=2, r_scale=R_SCALE)
                for tau, val in enumerate(mse, start=1):
                    rows.append({
                        "dataset":  ds,
                        "seed":     seed,
                        "channel":  c,
                        "scale":    tau,
                        "sampen_2d": float(val) if np.isfinite(val) else np.nan,
                    })
            print(f"  {ds} seed={seed}: scales {MAX_SCALE} computed")
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "mse_raw.csv", index=False)
    return df


def aggregate(df):
    """Compute mean ± std per (dataset, scale) over 9 mosaics (3 seeds × 3 channels)."""
    agg = df.groupby(["dataset", "scale"]).agg(
        mean=("sampen_2d", "mean"),
        std=("sampen_2d", "std"),
        n_finite=("sampen_2d", lambda s: s.notna().sum()),
    ).reset_index()
    return agg


def fig_curves(agg, log=False):
    fig, ax = plt.subplots(figsize=(8.5, 5))
    for ds in DATASETS:
        sub = agg[agg["dataset"] == ds].sort_values("scale")
        ax.plot(sub["scale"], sub["mean"], color=DS_COLOR[ds], marker="o",
                linewidth=2, markersize=6, label=ds)
        ax.fill_between(sub["scale"], sub["mean"] - sub["std"], sub["mean"] + sub["std"],
                        color=DS_COLOR[ds], alpha=0.18)
    ax.set_xlabel(r"Escala $\tau$ (coarse-graining 2D)")
    ax.set_ylabel(r"SampEn$_{2D}$ (mosaico coarse-grained)")
    ax.set_title("MSE 2D dos mosaicos da conv1 — 3 datasets, mean $\\pm 1\\sigma$ entre 9 mosaicos")
    if log:
        ax.set_yscale("log")
    ax.set_xticks(range(1, MAX_SCALE + 1))
    ax.grid(alpha=0.3); ax.legend()
    plt.tight_layout()
    suffix = "_log" if log else ""
    plt.savefig(OUT / f"mse_f1_curves{suffix}.pdf"); plt.savefig(OUT / f"mse_f1_curves{suffix}.png")
    plt.close()
    print(f"MSE-F1{suffix} ok")


def write_table(agg):
    """Pivot to (scales × datasets) for the LaTeX table."""
    pivot = agg.pivot(index="scale", columns="dataset", values="mean")
    pivot_std = agg.pivot(index="scale", columns="dataset", values="std")
    pivot.to_csv(OUT / "mse_table.csv")

    lines = [
        "% Auto-generated by scripts/make_mse2d_figs.py",
        "\\begin{table}[H]",
        "\\centering",
        "\\caption{$\\mathrm{SampEn}_{2D}$ multiescala dos mosaicos $56\\times 56$ "
        "da \\texttt{conv1} (mean $\\pm 1\\sigma$ entre 3 sementes $\\times$ 3 canais; "
        f"$r = {R_SCALE}\\,\\sigma$, fixo entre escalas).}}",
        "\\label{tab:mse2d-conv1}",
        "\\small",
        "\\begin{tabular}{ccccc}",
        "\\toprule",
        "Escala $\\tau$ & Dim.~coarse & PathMNIST & OrganAMNIST & BloodMNIST \\\\",
        "\\midrule",
    ]
    for tau in range(1, MAX_SCALE + 1):
        coarse_dim = 56 // tau
        cells = [str(tau), f"${coarse_dim} \\times {coarse_dim}$"]
        for ds in DATASETS:
            m = pivot.loc[tau, ds]
            s = pivot_std.loc[tau, ds]
            if np.isnan(m):
                cells.append("---")
            else:
                cells.append(f"${m:.2f} \\pm {s:.2f}$")
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "mse_table.tex").write_text("\n".join(lines) + "\n")
    print("MSE-table ok")


def main():
    df = collect()
    agg = aggregate(df)
    print("\nAggregated MSE 2D per (dataset, scale):")
    pivot = agg.pivot(index="scale", columns="dataset", values="mean")
    print(pivot.to_string(float_format=lambda x: f"{x:.3f}"))
    fig_curves(agg, log=False)
    fig_curves(agg, log=True)
    write_table(agg)


if __name__ == "__main__":
    main()
