"""
src/writer.py — Thesis writer powered by Claude CLI (claude -p).

Responsibilities:
  1. Summarise experimental results from results/ CSVs.
  2. For each writable thesis section: check lock → build prompt → call Claude
     → wrap in \\begin{claudedraft}...\\end{claudedraft} → write atomically.
  3. Persist section locks (tese/.writer_locks.json).
  4. Persist provenance metadata (tese/.writer_provenance.json).

Usage (from orchestrator — triggered every N completed runs):
    python src/writer.py --results-dir results/ [--dry-run]

Usage (manual):
    python src/writer.py --section results/overview   # write one section
    python src/writer.py --lock   results/lmc_analysis
    python src/writer.py --unlock results/lmc_analysis
    python src/writer.py --status

Section markers in .tex files:
    % WRITER:BEGIN:{section_id}
    ...content generated by this script...
    % WRITER:END:{section_id}

Locking a section prevents the writer from overwriting it in future runs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
import os
import re
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

log = logging.getLogger(__name__)

# ============================================================================
# Paths and registries
# ============================================================================

TESE_DIR        = Path('tese')
LOCKS_FILE      = TESE_DIR / '.writer_locks.json'
PROVENANCE_FILE = TESE_DIR / '.writer_provenance.json'
DEFAULT_MODEL   = 'claude-opus-4-7'

# Registry of auto-writable thesis sections.
# 'file' is relative to the project root.
SECTIONS: dict[str, dict] = {
    'results/overview': {
        'file':        'tese/capitulos/resultados.tex',
        'description': 'Visão geral dos experimentos completados',
        'min_runs':    1,
    },
    'results/lmc_analysis': {
        'file':        'tese/capitulos/resultados.tex',
        'description': 'Análise da complexidade LMC por grupo de camada',
        'min_runs':    3,
    },
    'results/sampen_analysis': {
        'file':        'tese/capitulos/resultados.tex',
        'description': 'Análise da Entropia de Amostra 1D por grupo de camada',
        'min_runs':    3,
    },
}

# ============================================================================
# Lock management
# ============================================================================

def _load_json(path: Path) -> dict:
    return json.loads(path.read_text()) if path.exists() else {}


def _save_json(data: dict, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False))


def load_locks(locks_file: Path = LOCKS_FILE) -> dict:
    return _load_json(locks_file)


def save_locks(locks: dict, locks_file: Path = LOCKS_FILE) -> None:
    _save_json(locks, locks_file)


def is_locked(section_id: str, locks_file: Path = LOCKS_FILE) -> bool:
    return section_id in load_locks(locks_file)


def lock_section(
    section_id: str,
    locked_by: str = 'user',
    locks_file: Path = LOCKS_FILE,
) -> None:
    locks = load_locks(locks_file)
    locks[section_id] = {
        'locked_at': datetime.now(timezone.utc).isoformat(),
        'locked_by': locked_by,
    }
    save_locks(locks, locks_file)
    log.info("Locked section '%s'", section_id)


def unlock_section(section_id: str, locks_file: Path = LOCKS_FILE) -> None:
    locks = load_locks(locks_file)
    if section_id in locks:
        del locks[section_id]
        save_locks(locks, locks_file)
        log.info("Unlocked section '%s'", section_id)
    else:
        log.warning("Section '%s' was not locked", section_id)


# ============================================================================
# Provenance
# ============================================================================

def load_provenance(prov_file: Path = PROVENANCE_FILE) -> dict:
    return _load_json(prov_file)


def update_provenance(
    section_id: str,
    metadata: dict,
    prov_file: Path = PROVENANCE_FILE,
) -> None:
    prov = load_provenance(prov_file)
    prov[section_id] = {
        'generated_at': datetime.now(timezone.utc).isoformat(),
        **metadata,
    }
    _save_json(prov, prov_file)


# ============================================================================
# LaTeX section I/O
# ============================================================================

_BEGIN_FMT = '% WRITER:BEGIN:{}'
_END_FMT   = '% WRITER:END:{}'


def wrap_claudedraft(text: str) -> str:
    """Wrap text in the claudedraft LaTeX environment."""
    return f'\\begin{{claudedraft}}\n{text.strip()}\n\\end{{claudedraft}}'


def read_tex_section(tex_file: Path, section_id: str) -> Optional[str]:
    """
    Return the current content between WRITER markers, or None if not found.
    """
    if not tex_file.exists():
        return None
    begin = _BEGIN_FMT.format(section_id)
    end   = _END_FMT.format(section_id)
    text  = tex_file.read_text(encoding='utf-8')
    pat   = re.compile(
        rf'{re.escape(begin)}\n(.*?)\n{re.escape(end)}',
        re.DOTALL,
    )
    m = pat.search(text)
    return m.group(1) if m else None


def write_tex_section(
    tex_file: Path,
    section_id: str,
    content: str,
) -> bool:
    """
    Atomically replace (or append) the content between WRITER markers.
    Returns True if the file was modified.
    """
    begin = _BEGIN_FMT.format(section_id)
    end   = _END_FMT.format(section_id)

    current = tex_file.read_text(encoding='utf-8') if tex_file.exists() else ''

    if begin not in current:
        new = current + f'\n{begin}\n{content}\n{end}\n'
    else:
        pat = re.compile(
            rf'({re.escape(begin)})(.*?)({re.escape(end)})',
            re.DOTALL,
        )
        new = pat.sub(
            lambda m: m.group(1) + f'\n{content}\n' + m.group(3),
            current,
        )

    if new == current:
        return False

    tex_file.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=tex_file.parent, suffix='.tmp')
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write(new)
        Path(tmp).replace(tex_file)
    except Exception:
        Path(tmp).unlink(missing_ok=True)
        raise

    return True


# ============================================================================
# Results summarisation
# ============================================================================

def summarise_results(results_dir: Path) -> dict:
    """
    Load results/results.csv and per-run metrics.csv files.
    Returns a structured dict suitable for injecting into prompts.
    """
    try:
        import pandas as pd
    except ImportError:
        return {'n_completed': 0, 'runs': [], 'metrics': []}

    results_csv = results_dir / 'results.csv'
    if not results_csv.exists():
        return {'n_completed': 0, 'runs': [], 'metrics': []}

    df = pd.read_csv(results_csv)
    summary: dict = {
        'n_completed':  int(len(df)),
        'datasets':     sorted(df['dataset'].unique().tolist()),
        'epochs_range': [int(df['epochs'].min()), int(df['epochs'].max())],
        'seeds':        sorted(df['seed'].unique().tolist()),
        'mean_val_acc': round(float(df['final_val_acc'].mean()), 4)
                        if 'final_val_acc' in df.columns else None,
        'runs':         df[['run_id', 'dataset', 'epochs', 'seed',
                             'final_val_acc', 'final_val_loss']].to_dict('records'),
    }

    # Per-group metrics averages across all runs
    metrics_rows = []
    runs_dir = results_dir / 'runs'
    for run_id in df['run_id']:
        m_path = runs_dir / str(run_id) / 'metrics.csv'
        if not m_path.exists():
            continue
        m = pd.read_csv(m_path)
        for grp in m['group'].unique():
            sub = m[m['group'] == grp]
            se  = pd.to_numeric(sub['sampen_1d'], errors='coerce')
            metrics_rows.append({
                'run_id':     run_id,
                'group':      grp,
                'lmc_mean':   round(float(sub['lmc_complexity'].mean()), 6),
                'lmc_std':    round(float(sub['lmc_complexity'].std()), 6),
                'sampen_mean': round(float(se.mean()), 4) if se.notna().any() else None,
                'l2_mean':    round(float(sub['l2_mean'].mean()), 4),
            })
    summary['metrics'] = metrics_rows
    return summary


# ============================================================================
# Prompt construction
# ============================================================================

_SYSTEM_PREAMBLE = (
    "You are writing a section of a Brazilian Portuguese master's thesis "
    "(FFCLRP-USP, Programa de Pós-Graduação em Computação Aplicada). "
    "The thesis investigates whether statistical complexity of deep neural "
    "network weights (LMC and Sample Entropy) constitutes an objective "
    "overfitting marker. "
    "Write FORMAL BRAZILIAN PORTUGUESE. "
    "Output ONLY LaTeX paragraphs — no section headers, no \\begin{document}. "
    "Do NOT use placeholder phrases like 'os resultados mostram que ...' without "
    "grounding them in the provided data."
)

_SECTION_INSTRUCTIONS: dict[str, str] = {
    'results/overview': (
        "Write 2–3 paragraphs describing: (1) the experimental setup "
        "(dataset, architecture, optimizer, number of completed runs), "
        "(2) the overall validation accuracy achieved, "
        "(3) a brief note that per-group complexity trajectories are analysed in "
        "subsequent sections."
    ),
    'results/lmc_analysis': (
        "Write 3–4 paragraphs analysing the LMC statistical complexity "
        "(C = H × D, in bits × L2) trajectories for each layer group "
        "(conv, dense, bn_gamma, bn_beta). "
        "Comment on whether the trajectories are monotonic or show inflection "
        "points, and whether groups differ systematically. "
        "Reference specific numeric values from the data."
    ),
    'results/sampen_analysis': (
        "Write 3–4 paragraphs analysing the 1D Sample Entropy (SampEn₁D) "
        "trajectories of the flattened weight distributions for each layer group. "
        "Discuss how entropy evolves during training and whether it correlates "
        "with the LMC complexity trends described in the previous section. "
        "Reference specific numeric values from the data."
    ),
}


def build_prompt(section_id: str, data: dict) -> str:
    instruction = _SECTION_INSTRUCTIONS.get(
        section_id,
        'Write 2–3 paragraphs summarising the provided experimental data.',
    )
    data_str = json.dumps(data, ensure_ascii=False, indent=2, default=str)
    # Truncate to avoid hitting context limits
    if len(data_str) > 4_000:
        data_str = data_str[:4_000] + '\n... [truncated]'

    return (
        f"{_SYSTEM_PREAMBLE}\n\n"
        f"Section task:\n{instruction}\n\n"
        f"Experimental data:\n{data_str}\n"
    )


# ============================================================================
# Claude CLI invocation
# ============================================================================

def call_claude(
    prompt: str,
    model: str = DEFAULT_MODEL,
    timeout: int = 120,
) -> Optional[str]:
    """
    Invoke `claude --model MODEL --print PROMPT` and return stdout.
    Returns None if the claude CLI is unavailable or exits non-zero.
    """
    try:
        result = subprocess.run(
            ['claude', '--model', model, '--print', prompt],
            capture_output=True,
            text=True,
            timeout=timeout,
        )
    except FileNotFoundError:
        log.warning(
            "claude CLI not found — install Claude Code or add it to PATH"
        )
        return None
    except subprocess.TimeoutExpired:
        log.error("claude CLI timed out after %d s", timeout)
        return None

    if result.returncode != 0:
        log.error("claude CLI exited %d: %s", result.returncode,
                  result.stderr[:200])
        return None

    return result.stdout.strip() or None


# ============================================================================
# High-level write pipeline
# ============================================================================

def write_section(
    section_id: str,
    results_dir: Path,
    model: str = DEFAULT_MODEL,
    dry_run: bool = False,
    locks_file: Path = LOCKS_FILE,
    prov_file: Path = PROVENANCE_FILE,
) -> bool:
    """
    Full pipeline for one section: check lock → summarise → prompt → write.

    Returns True if the section was written (or would be in dry-run mode),
    False if skipped (locked, not enough runs, or Claude unavailable).
    """
    cfg = SECTIONS.get(section_id)
    if cfg is None:
        log.error("Unknown section '%s'. Available: %s",
                  section_id, list(SECTIONS))
        return False

    if is_locked(section_id, locks_file):
        log.info("Section '%s' is locked — skipping", section_id)
        return False

    data = summarise_results(results_dir)
    min_runs = cfg.get('min_runs', 1)
    if data['n_completed'] < min_runs:
        log.info(
            "Section '%s' requires ≥ %d runs; only %d available — skipping",
            section_id, min_runs, data['n_completed'],
        )
        return False

    prompt = build_prompt(section_id, data)
    prompt_hash = hashlib.sha256(prompt.encode()).hexdigest()[:12]

    if dry_run:
        log.info("[DRY RUN] Would write section '%s' (prompt_hash=%s)",
                 section_id, prompt_hash)
        return True

    generated = call_claude(prompt, model=model)
    if generated is None:
        log.warning("Claude returned nothing for section '%s'", section_id)
        return False

    content = wrap_claudedraft(generated)
    tex_file = Path(cfg['file'])

    changed = write_tex_section(tex_file, section_id, content)
    if changed:
        log.info("Wrote section '%s' → %s", section_id, tex_file)
    else:
        log.info("Section '%s' unchanged", section_id)

    update_provenance(section_id, {
        'model':       model,
        'prompt_hash': prompt_hash,
        'word_count':  len(generated.split()),
        'n_runs':      data['n_completed'],
    }, prov_file)

    return True


# ============================================================================
# Status report
# ============================================================================

def print_status(
    results_dir: Path,
    locks_file: Path = LOCKS_FILE,
    prov_file: Path = PROVENANCE_FILE,
) -> None:
    locks = load_locks(locks_file)
    prov  = load_provenance(prov_file)
    data  = summarise_results(results_dir)

    print(f"\nWriter status  —  {data['n_completed']} runs completed\n")
    print(f"{'Section':<35}  {'Status':<12}  {'Last generated':<26}  {'n_runs'}")
    print('─' * 90)

    for sid, cfg in SECTIONS.items():
        if sid in locks:
            status = 'LOCKED'
        elif data['n_completed'] < cfg.get('min_runs', 1):
            status = 'insufficient'
        else:
            status = 'writable'

        p = prov.get(sid, {})
        gen_at   = p.get('generated_at', '—')[:19]
        n_runs   = p.get('n_runs', '—')
        print(f"{sid:<35}  {status:<12}  {gen_at:<26}  {n_runs}")

    print()


# ============================================================================
# CLI entry-point
# ============================================================================

def _parse_args(argv=None):
    p = argparse.ArgumentParser(
        description='Write thesis sections from experimental results using Claude.'
    )
    group = p.add_mutually_exclusive_group()
    group.add_argument('--section',    metavar='ID',
                       help='Write a specific section (default: all unlocked)')
    group.add_argument('--lock',       metavar='ID',
                       help='Lock a section (prevent future overwrites)')
    group.add_argument('--unlock',     metavar='ID',
                       help='Unlock a previously locked section')
    group.add_argument('--status',     action='store_true',
                       help='Print status of all sections and exit')

    p.add_argument('--results-dir',  default='results',
                   help='Root directory of experiment outputs (default: results/)')
    p.add_argument('--model',        default=DEFAULT_MODEL,
                   help=f'Claude model to use (default: {DEFAULT_MODEL})')
    p.add_argument('--n-completed',  type=int, default=None,
                   help='Number of completed runs (informational, from orchestrator)')
    p.add_argument('--dry-run',      action='store_true',
                   help='Show what would be written without calling Claude')
    p.add_argument('--log-level',    default='INFO',
                   choices=['DEBUG', 'INFO', 'WARNING', 'ERROR'])
    return p.parse_args(argv)


def main(argv=None) -> None:
    args = _parse_args(argv)
    logging.basicConfig(
        level=getattr(logging, args.log_level),
        format='%(asctime)s  %(levelname)s  %(name)s  %(message)s',
        datefmt='%H:%M:%S',
    )

    results_dir = Path(args.results_dir)

    if args.status:
        print_status(results_dir, LOCKS_FILE, PROVENANCE_FILE)
        return

    if args.lock:
        TESE_DIR.mkdir(parents=True, exist_ok=True)
        lock_section(args.lock, locks_file=LOCKS_FILE)
        return

    if args.unlock:
        unlock_section(args.unlock, locks_file=LOCKS_FILE)
        return

    sections_to_write = (
        [args.section] if args.section else list(SECTIONS.keys())
    )

    n_written = 0
    for sid in sections_to_write:
        if write_section(sid, results_dir, model=args.model,
                         dry_run=args.dry_run,
                         locks_file=LOCKS_FILE,
                         prov_file=PROVENANCE_FILE):
            n_written += 1

    log.info('%d section(s) written', n_written)


if __name__ == '__main__':
    main()
